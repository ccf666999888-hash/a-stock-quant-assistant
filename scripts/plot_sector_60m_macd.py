def latest_trade_date() -> str:
    with duckdb.connect(str(DB_PATH), read_only=True) as con:
        latest = con.execute("select max(trade_date) from daily_price").fetchone()[0]
    if not latest:
        raise RuntimeError("daily_price is empty; update daily data first")
    return str(latest)


def date_window(
    end_date: str | None,
    months: int | None = None,
    days: int | None = None,
) -> tuple[str, str]:
    end = end_date or latest_trade_date()
    if days is not None:
        if days < 1:
            raise ValueError("days must be >= 1")
        start = (pd.to_datetime(end) - pd.Timedelta(days=days - 1)).strftime("%Y%m%d")
    elif months is not None:
        if months < 1:
            raise ValueError("months must be >= 1")
        start = (pd.to_datetime(end) - pd.DateOffset(months=months)).strftime("%Y%m%d")
    else:
        start = (pd.to_datetime(end) - pd.Timedelta(days=59)).strftime("%Y%m%d")
    return start, end


