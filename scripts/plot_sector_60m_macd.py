def add_macd(frame: pd.DataFrame) -> pd.DataFrame:
    frame = frame.copy().sort_values("trade_time").reset_index(drop=True)
    close = frame["close"].astype(float)
    frame["ema12"] = close.ewm(span=12, adjust=False).mean()
    frame["ema26"] = close.ewm(span=26, adjust=False).mean()
    frame["dif"] = frame["ema12"] - frame["ema26"]
    frame["dea"] = frame["dif"].ewm(span=9, adjust=False).mean()
    frame["macd"] = (frame["dif"] - frame["dea"]) * 2
    for window in (5, 10, 20):
        frame[f"ma{window}"] = close.rolling(window).mean()
    frame["bias5"] = (frame["close"] / frame["ma5"] - 1) * 100
    frame["bias10"] = (frame["close"] / frame["ma10"] - 1) * 100
    frame["bias20"] = (frame["close"] / frame["ma20"] - 1) * 100
    frame["above_ma5"] = frame["close"] > frame["ma5"]
    frame["above_ma10"] = frame["close"] > frame["ma10"]
    frame["above_ma20"] = frame["close"] > frame["ma20"]
    frame["dif_gt_dea"] = frame["dif"] > frame["dea"]
    frame["dif_up"] = frame["dif"] > frame["dif"].shift(1)
    frame["macd_up"] = frame["macd"] > frame["macd"].shift(1)
    frame["golden"] = (frame["dif"] > frame["dea"]) & (
        frame["dif"].shift(1) <= frame["dea"].shift(1)
    )
    frame["death"] = (frame["dif"] < frame["dea"]) & (
        frame["dif"].shift(1) >= frame["dea"].shift(1)
    )
    frame["green_shrink_3"] = (
        (frame["macd"] < 0)
        & (frame["macd"].diff() > 0)
        & (frame["macd"].diff().shift(1) > 0)
    )
    frame["red_shrink_3"] = (
        (frame["macd"] > 0)
        & (frame["macd"].diff() < 0)
        & (frame["macd"].diff().shift(1) < 0)
    )
    return frame


def classify_latest(frame: pd.DataFrame) -> str:
    latest = frame.iloc[-1]
    prev = frame.iloc[-2] if len(frame) > 1 else latest
    above_all = bool(latest["above_ma5"] and latest["above_ma10"] and latest["above_ma20"])
    below_all = bool(
        latest["close"] < latest["ma5"]
        and latest["close"] < latest["ma10"]
        and latest["close"] < latest["ma20"]
    )
    if latest["macd"] > 0 and bool(latest["red_shrink_3"]) and (
        latest["close"] < latest["ma5"] or latest["dif"] < prev["dif"]
    ):
        return "逃顶预警"
    if (
        above_all
        and latest["dif_gt_dea"]
        and latest["macd"] > 0
        and latest["macd_up"]
        and latest["dif_up"]
    ):
        return "强势延续"
    if above_all and latest["dif_gt_dea"] and latest["macd"] > 0:
        return "强势放缓"
    if (
        bool(latest["green_shrink_3"])
        and latest["dif_up"]
        and (latest["above_ma5"] or latest["above_ma10"])
    ):
        return "抄底观察"
    if latest["above_ma20"] and latest["dif_gt_dea"] and latest["macd"] > 0:
        return "反弹确认"
    if below_all and not latest["dif_gt_dea"] and latest["macd"] < 0:
        return "弱势回避"
    if latest["close"] < latest["ma20"] and not latest["dif_gt_dea"]:
        return "下跌延续"
    return "震荡观察"


def rule_stats(frame: pd.DataFrame) -> dict[str, float | int]:
    data = frame.copy()
    data["fwd4_ret"] = data["close"].shift(-4) / data["close"] - 1
    data["fwd8_ret"] = data["close"].shift(-8) / data["close"] - 1
    bottom_confirm = (
        data["above_ma5"]
        & data["above_ma10"]
        & data["above_ma20"]
        & data["dif_gt_dea"]
        & (data["macd"] > 0)
        & data["macd_up"]
    )
    bottom_watch = (
        data["green_shrink_3"]
        & data["dif_up"]
        & (data["above_ma5"] | data["above_ma10"])
    )
    top_confirm = (
        (data["close"] < data["ma10"])
        & (data["close"] < data["ma20"])
        & (~data["dif_gt_dea"])
        & (data["macd"] < 0)
    )
    top_watch = (
        data["red_shrink_3"]
        & ((data["close"] < data["ma5"]) | (~data["dif_up"]))
        & (data["macd"] > 0)
    )

    def summarize(mask: pd.Series, direction: str) -> tuple[int, float, float]:
        sample = data[mask & data["fwd4_ret"].notna()]
        if sample.empty:
            return 0, np.nan, np.nan
        avg = float(sample["fwd4_ret"].mean() * 100)
        if direction == "up":
            rate = float((sample["fwd4_ret"] > 0).mean() * 100)
        else:
            rate = float((sample["fwd4_ret"] < 0).mean() * 100)
        return len(sample), avg, rate

    bc_n, bc_avg, bc_rate = summarize(bottom_confirm, "up")
    bw_n, bw_avg, bw_rate = summarize(bottom_watch, "up")
    tc_n, tc_avg, tc_rate = summarize(top_confirm, "down")
    tw_n, tw_avg, tw_rate = summarize(top_watch, "down")
    return {
        "bottom_confirm_n": bc_n,
        "bottom_confirm_fwd4_avg_pct": bc_avg,
        "bottom_confirm_up_rate_pct": bc_rate,
        "bottom_watch_n": bw_n,
        "bottom_watch_fwd4_avg_pct": bw_avg,
        "bottom_watch_up_rate_pct": bw_rate,
        "top_confirm_n": tc_n,
        "top_confirm_fwd4_avg_pct": tc_avg,
        "top_confirm_down_rate_pct": tc_rate,
        "top_watch_n": tw_n,
        "top_watch_fwd4_avg_pct": tw_avg,
        "top_watch_down_rate_pct": tw_rate,
    }


def draw_candles(ax: plt.Axes, frame: pd.DataFrame) -> None:
    width = 0.58
    up_color = "#D84A3A"
    down_color = "#2E9F6E"
    flat_color = "#7A828F"
    for i, row in frame.iterrows():
        open_price = float(row["open"])
        close_price = float(row["close"])
        high = float(row["high"])
        low = float(row["low"])
        color = up_color if close_price > open_price else down_color if close_price < open_price else flat_color
        ax.vlines(i, low, high, color=color, linewidth=0.9, zorder=2)
        lower = min(open_price, close_price)
        height = abs(close_price - open_price)
        if height < 0.03:
            ax.hlines(close_price, i - width / 2, i + width / 2, color=color, linewidth=1.1)
        else:
            ax.add_patch(
                Rectangle(
                    (i - width / 2, lower),
                    width,
                    height,
                    facecolor=color,
                    edgecolor=color,
                    linewidth=0.6,
                    zorder=3,
                )
            )
    ax.set_xlim(-1, len(frame))


def format_x_axis(ax: plt.Axes, frame: pd.DataFrame) -> None:
    labels = frame["trade_time"].dt.strftime("%m-%d\n%H:%M").tolist()
    step = max(1, len(frame) // 9)
    ticks = np.arange(len(frame))[::step]
    ax.set_xticks(ticks)
    ax.set_xticklabels([labels[i] for i in ticks], rotation=0)


def safe_name(value: str) -> str:
    return re.sub(r'[\\/:*?"<>|\\s]+', "_", value.strip())


